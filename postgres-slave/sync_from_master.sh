#!/bin/bash

MASTER_HOST=postgres
MASTER_PORT=5432
MASTER_DB=${DATABASE_NAME}
MASTER_USER=${DATABASE_USER}
MASTER_PASSWORD=${DATABASE_PASSWORD}
SLAVE_DB=${DATABASE_NAME}
DUMP_FILE=/tmp/db.dump

export PGPASSWORD=$MASTER_PASSWORD

pg_dump -h $MASTER_HOST -p $MASTER_PORT -U $MASTER_USER -Fc $MASTER_DB -f $DUMP_FILE

dropdb -U $MASTER_USER --if-exists $SLAVE_DB
createdb -U $MASTER_USER $SLAVE_DB
pg_restore -U $MASTER_USER -d $SLAVE_DB $DUMP_FILE

rm -f $DUMP_FILE
